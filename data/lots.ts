function makeCartons(prefix: string, startNum: number, count: number, skus: string[]): Carton[] {
  const cartons: Carton[] = [];
  for (let i = 0; i < count; i++) {
    const sealId = `${prefix}-${startNum + i}`;
    cartons.push({ sealId, lines: [skus[i % skus.length]] });
  }
  return cartons;
}

